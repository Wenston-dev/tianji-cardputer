void lotNumber(int n, char* out) {
  static const char* d[] = {"", "一", "二", "三", "四", "五", "六", "七", "八", "九"};
  strcpy(out, "第");
  if (n >= 20) strcat(out, d[n / 10]);
  if (n >= 10) strcat(out, "十");
  strcat(out, d[n % 10]);
  strcat(out, "签");
}

