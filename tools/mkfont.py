#!/usr/bin/env python3
"""Build VLW smooth fonts (as C arrays) containing only the glyphs the firmware uses.

Scans the sketch sources for non-ASCII characters, renders them with Source Han Sans
(SIL OFL) at several sizes/weights and writes fontdata.cpp.
"""
import glob, os, struct, sys
from PIL import Image, ImageDraw, ImageFont

SKETCH = sys.argv[1] if len(sys.argv) > 1 else "tianji"

def find_font():
    """Source Han Sans variable OTF: $SOURCE_HAN_SANS, or any SourceHanSans*VF*.otf in common font folders."""
    env = os.environ.get("SOURCE_HAN_SANS")
    if env:
        return env if os.path.isfile(env) else None
    for d in ("~/Library/Fonts", "/Library/Fonts", "~/.fonts", "~/.local/share/fonts", "/usr/share/fonts", "."):
        hits = sorted(glob.glob(os.path.join(os.path.expanduser(d), "**", "SourceHanSans*VF*.otf"), recursive=True))
        if hits:
            return hits[0]
    return None


FONT = find_font()
if not FONT:
    sys.exit("Source Han Sans (variable OTF) not found. Download it from "
             "https://github.com/adobe-fonts/source-han-sans and set SOURCE_HAN_SANS=/path/to/font.otf")

chars = set(chr(c) for c in range(0x20, 0x7F))
chars |= set("·—…“”‘’《》「」、。，；：？！（）·°×÷←→↑↓")
for path in glob.glob(os.path.join(SKETCH, "*.*")):
    if path.endswith((".cpp", ".h", ".ino", ".inc")) and not path.endswith("fontdata.cpp"):
        for ch in open(path, encoding="utf-8").read():
            if ord(ch) >= 0x80 and ord(ch) <= 0xFFFF:
                chars.add(ch)
chars.discard("　")

def vlw(size, weight, charset):
    f = ImageFont.truetype(FONT, size)
    f.set_variation_by_name(weight)
    asc, desc = f.getmetrics()
    glyphs = []
    for ch in sorted(charset, key=ord):
        adv = int(round(f.getlength(ch)))
        l, t, r, b = f.getbbox(ch, anchor="ls")
        w, h = max(0, r - l), max(0, b - t)
        if ch == " " or w == 0 or h == 0:
            glyphs.append((ord(ch), 0, 0, adv, 0, 0, b""))
            continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-l, -t), ch, font=f, fill=255, anchor="ls")
        glyphs.append((ord(ch), h, w, adv, -t, l, img.tobytes()))
    out = struct.pack(">6i", len(glyphs), 11, size, 0, asc, desc)
    for g in glyphs:
        out += struct.pack(">7i", g[0], g[1], g[2], g[3], g[4], g[5], 0)
    for g in glyphs:
        out += g[6]
    return out

fonts = [
    ("FONT_F12", 12, "Medium", chars),
    ("FONT_F16", 16, "Regular", chars),
    ("FONT_F24", 24, "Light", chars),
    ("FONT_FBIG", 34, "ExtraLight", set("0123456789,.:-+% ")),
]
with open(os.path.join(SKETCH, "fontdata.cpp"), "w") as o:
    o.write("// Generated by tools/mkfont.py from Source Han Sans (SIL Open Font License). Do not edit.\n")
    o.write("#include <stdint.h>\n\n")
    for name, size, weight, cs in fonts:
        data = vlw(size, weight, cs)
        o.write(f"extern const uint8_t {name}[] = {{\n")
        for i in range(0, len(data), 32):
            o.write(",".join(str(b) for b in data[i:i + 32]) + ",\n")
        o.write("};\n\n")
        print(f"{name}: {len(cs)} glyphs, {len(data)/1024:.0f} KB")
